package frc.team5712.path.wpilib;

/**
 * An editor named point, checked by the compiler: the editor generates {@code PathEditorNames.Points},
 * implementing this, for {@link PathLibrary#namedPoint(PointId)} and {@link Pathfinding#toPoint}.
 */
public interface PointId {
  /** The point's name as the editor shows it. */
  String pointName();
}
