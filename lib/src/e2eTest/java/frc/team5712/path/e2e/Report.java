package frc.team5712.path.e2e;

import frc.team5712.path.core.FieldFrame;
import frc.team5712.path.e2e.EndToEndRun.EventResult;
import frc.team5712.path.e2e.EndToEndRun.Segment;
import frc.team5712.path.e2e.PathEndToEndTest.Row;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;

/** e2e/RESULTS.md: the table of every path × framework × alliance, with the worst errors. */
final class Report {
  private Report() {}

  private static String alliance(FieldFrame f) {
    return switch (f) {
      case BLUE -> "blue";
      case RED_HALF_TURN -> "red (half-turn)";
      case RED_MIRROR -> "red (mirror)";
    };
  }

  private static String f(String format, Object... args) {
    return String.format(Locale.ROOT, format, args);
  }

  /** The event result with the largest |value|, or null. */
  private static EventResult worstEvent(List<Row> rows, java.util.function.ToDoubleFunction<EventResult> key) {
    return rows.stream().flatMap(r -> r.full().events.stream())
        .max(Comparator.comparingDouble(e -> Math.abs(key.applyAsDouble(e)))).orElse(null);
  }

  static String markdown(List<Row> rows) {
    StringBuilder out = new StringBuilder();
    long passed = rows.stream().filter(Row::pass).count();
    long events = rows.stream().mapToLong(r -> r.full().events.size()).sum();
    EventResult worstPos = worstEvent(rows, EventResult::positionError);
    EventResult worstTime = worstEvent(rows, EventResult::timeError);
    double minArrive = Double.POSITIVE_INFINITY;
    double maxArrive = Double.NEGATIVE_INFINITY;
    double maxSettle = 0;
    double worstPeak = 0;
    String worstPeakWhere = "";
    double worstShare = 0;
    for (Row r : rows) {
      for (EventResult e : r.full().events) {
        worstShare = Math.max(worstShare, Math.abs(e.positionError()) / e.positionTolerance());
      }
      for (Segment s : r.full().segments) {
        if (Double.isNaN(s.finishT)) {
          continue;
        }
        double gap = (s.arriveT - s.startT) - s.arrivalDue;
        if (s.path.spec().endMetersPerSecond() == 0) {
          minArrive = Math.min(minArrive, gap);
          maxArrive = Math.max(maxArrive, gap);
          maxSettle = Math.max(maxSettle, s.finishT - s.arriveT);
        }
        double peak = s.preview.peakMetersPerSecond();
        double peakGap = Math.abs(s.peakSpeed - peak) / Math.max(peak, 1e-9);
        if (peak > 0.5 && peakGap > worstPeak) {
          worstPeak = peakGap;
          worstPeakWhere = s.name + ", " + r.framework() + ", " + alliance(r.frame());
        }
      }
    }

    out.append("# End-to-end results (phase 6)\n\n");
    out.append("Generated by `node tools/e2e.mjs` (or `npm --prefix editor/app run e2e:full`); don't edit by hand.\n\n");
    out.append("Every path was authored in the editor by Playwright (editor/app/e2e-author), saved through the editor's own\n");
    out.append("save flow, loaded with `PathLibrary.loadAll()`, and run by the real `PathFollower` inside `FollowPathCommand`\n");
    out.append("(Commands v3) and `FollowPathCommandV2` (Commands v2) on a simulated drivetrain at 50 Hz, on blue and both red\n");
    out.append("flips. Each row is two runs: one to the end, and one cancelled halfway through its previewed time.\n\n");
    out.append("## Summary\n\n");
    out.append(f("- **%d of %d rows pass** (%d paths and chains × 2 frameworks × 3 alliances).\n", passed, rows.size(), rows.size() / 6));
    out.append(f("- **%d events** fired and checked in the full runs.\n", events));
    if (worstPos != null) {
      out.append(f("- Worst event position error (true pose when the event's command ran, along the path, versus where it was\n"
          + "  authored): **%+.1f cm** (%s, `%s` at %.2f m).\n", worstPos.positionError() * 100, worstPos.path(), worstPos.name(), worstPos.authoredS()));
      out.append(f("- Worst event time error (versus the preview's t(s), or for an event at a stop the plan's time into the\n"
          + "  finish band): **%+.3f s** (%s, `%s`).\n",
          worstTime.timeError(), worstTime.path(), worstTime.name()));
    }
    out.append(f("- The worst event position error was **%.0f %%** of its allowance (3 cm, or half a loop of travel plus 1 cm at speed).\n",
        worstShare * 100));
    out.append(f("- Arrival in the finish band (2 cm, 1°) minus the plan's time into it, on paths that stop: **%+.3f to %+.3f s**.\n",
        minArrive, maxArrive));
    out.append(f("- Settling after arrival until the follower finishes (the DriveToPose finish, which the preview doesn't\n"
        + "  model): at most **%.2f s**.\n", maxSettle));
    out.append(f("- Worst peak-speed gap, robot (true) versus preview, on paths faster than 0.5 m/s: **%.1f %%** (%s).\n\n", worstPeak * 100, worstPeakWhere));

    out.append("## Tolerances (all in `lib/src/e2eTest/.../Tolerances.java`)\n\n");
    out.append("| Check | Pass mark |\n| --- | --- |\n");
    out.append(f("| Event position (true pose, along the path) | ±%.0f cm, or ±(v·%.0f ms + %.0f cm) at the planned speed v, whichever is more |\n",
        Tolerances.EVENT_POSITION_METERS * 100, Tolerances.LOOP_SECONDS * 500, Tolerances.EVENT_POSITION_MARGIN_METERS * 100));
    out.append(f("| Event time versus the preview's t(s) (an event at a stop: versus the plan's time into the finish band); arrival likewise | ±%.2f s |\n", Tolerances.EVENT_TIME_SECONDS));
    out.append(f("| End position / heading (true pose) | %.0f cm / %.1f° (rolling ends: plus one loop of travel) |\n",
        Tolerances.END_POSITION_METERS * 100, Tolerances.END_HEADING_DEGREES));
    out.append(f("| Settling after arrival (the DriveToPose finish) | at most %.2f s |\n", Tolerances.SETTLE_SECONDS));
    out.append(f("| Peak speed versus the preview's | ±%.0f %% (±%.2f m/s on slow paths) |\n",
        Tolerances.PEAK_SPEED_FRACTION * 100, Tolerances.PEAK_SPEED_ABSOLUTE));
    out.append(f("| Rolling hand-off | true speed stays above %.0f %% of the end speed |\n", Tolerances.HANDOFF_SPEED_FRACTION * 100));
    out.append("| Path work after pressing go | none: no geometry or profile built from `schedule` to the end |\n");
    out.append("| Interrupt | follower CANCELLED, nothing fires afterwards, what fired is a prefix of the order, robot stopped |\n\n");

    out.append("## Simulated drivetrain (`SimDrive`)\n\n");
    out.append(f("Field-relative velocity commands take effect after %.0f ms, then the chassis velocity follows them with a\n"
        + "first-order lag (τ = %.0f ms), integrated every %.0f ms. The robot code reads the true pose and velocity plus\n"
        + "Gaussian noise (σ %.0f mm, %.1f°, %.3f m/s), seeded per run. No slip or motor saturation: the follower's limiter\n"
        + "keeps commands inside the grip budget, and the bench models slip.\n\n",
        SimDrive.LATENCY_SECONDS * 1000, SimDrive.LAG_SECONDS * 1000, SimDrive.SUBSTEP_SECONDS * 1000,
        SimDrive.POSITION_NOISE_METERS * 1000, Math.toDegrees(SimDrive.HEADING_NOISE_RADIANS), SimDrive.VELOCITY_NOISE_METERS_PER_SECOND));
    out.append(f("The robot code is what a team would write: `FollowerConfig.defaults(robot)` with `latencySeconds` set to this\n"
        + "drivetrain's response delay, %.0f ms (latency, lag and half a loop of holding each command), as a team sets it\n"
        + "for its own robot. The robot file the editor saved plans spin at 7.5 rad/s and 10 rad/s², a little under the\n"
        + "follower's own 540°/s and 720°/s², so feedback has room, as the plan's grip (μ 0.7) sits under the limiter's.\n\n",
        SimDrive.RESPONSE_DELAY_SECONDS * 1000));
    out.append("## Why the robot and the preview differ where they do\n\n");
    out.append("- **Event positions.** A command can only start on a robot loop, and at 4 m/s the robot covers 8 cm between\n"
        + "  loops. The follower fires each event on the loop nearest to passing it, so the error is up to half a loop of\n"
        + "  travel either side; the allowance grows with the planned speed for that reason.\n");
    out.append("- **Events at a stop.** They fire when the robot gets inside the finish band (2 cm and 1°), which the plan\n"
        + "  itself enters a little before its last instant (about 0.08 s at 6 m/s² braking), so that is when they're due.\n");
    out.append("- **Settling.** The preview's total ends when the plan does. The follower then finishes with DriveToPose's law:\n"
        + "  slower than 5 cm/s, inside 2 cm and 1°, held for 0.1 s, after taking up any centimetre of overshoot from\n"
        + "  the drivetrain's delay.\n\n");

    out.append("## Every path × framework × alliance\n\n");
    out.append("| Path | Framework | Alliance | Result | Events | Worst event position | Worst event time | Arrival robot / plan | Settle | Peak robot / preview | Interrupt |\n");
    out.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for (Row r : rows) {
      EndToEndRun run = r.full();
      double arrival = 0;
      double previewTime = 0;
      double settle = 0;
      double peak = 0;
      double previewPeak = 0;
      for (Segment s : run.segments) {
        arrival += s.arriveT - s.startT;
        previewTime += s.path.spec().endMetersPerSecond() > 0 ? s.preview.totalTimeSeconds() : s.arrivalDue;
        settle = s.finishT - s.arriveT; // the last segment's
        peak = Math.max(peak, s.peakSpeed);
        previewPeak = Math.max(previewPeak, s.preview.peakMetersPerSecond());
      }
      out.append(f("| %s | %s | %s | %s | %d | %.1f cm | %.3f s | %.2f / %.2f s | %.2f s | %.2f / %.2f m/s | %s |\n",
          r.scenario(), r.framework(), alliance(r.frame()), r.pass() ? "pass" : "**FAIL**", run.events.size(),
          PathEndToEndTest.worst(run, EventResult::positionError) * 100, PathEndToEndTest.worst(run, EventResult::timeError),
          arrival, previewTime, settle, peak, previewPeak,
          r.interrupted().failures.isEmpty() ? f("pass (%d fired)", r.interrupted().fired.size()) : "**FAIL**"));
    }
    List<Row> failed = rows.stream().filter(r -> !r.pass()).toList();
    if (!failed.isEmpty()) {
      out.append("\n## Failures\n\n");
      for (Row r : failed) {
        out.append(f("- %s, %s, %s:\n", r.scenario(), r.framework(), alliance(r.frame())));
        r.full().failures.forEach(m -> out.append("  - ").append(m).append('\n'));
        r.interrupted().failures.forEach(m -> out.append("  - interrupted: ").append(m).append('\n'));
      }
    }
    return out.toString();
  }
}
