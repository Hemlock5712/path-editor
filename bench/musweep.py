"""Ours at four robot-file grips: `python bench/run.py --mu-sweep`.

PathPlanner plans corners at its wheel COF (the plant's static grip); ours' robot file gives the tread's mu
(ppcompare.MU_SWEEP: the shipped OURS_MU first, then lower). Each is run as drawn and after the optimiser
(re-run per mu, same budget and seed), on every --pp-compare target (the 2026 routes and the bench courses),
with a perfect pose and wheel odometry, and with slip-aware odometry on the bench courses. PathPlanner's rows
come from out/ppcompare.json (`--pp-compare`); its optimised rows are also run with slip-aware odometry here.

The output limiter's grip option (limiterFrictionCoefficient) is max(1.0, mu) in the sweep rows (ppcompare.py).
Braking stays as shipped.
"""

import json
import os
import time

import numpy as np

import ppcompare as P
from common import RP
from courses import COURSES

OUT = P.OUT
MD = P.MD
MU_START, MU_END = "<!-- musweep:start -->", "<!-- musweep:end -->"
PP_REF = ["pp2027_optimised", "pp_path2_optimised"]


def keys():
    return [P.mu_key(m) for m in P.MU_SWEEP] + [P.mu_key(m, True) for m in P.MU_SWEEP]


def run(seeds, procs):
    import multiprocessing as mp

    from run import agg

    names = list(P.targets())
    courses = [c for c in COURSES if c in names]  # the --pp-compare targets that are bench courses
    ks = keys()
    t0 = time.time()
    out = {"meta": {"seeds": seeds, "targets": names, "courses": courses, "mu": list(P.MU_SWEEP), "keys": ks},
           "runs": {}}
    with mp.get_context("spawn").Pool(procs) as pool:
        if not os.path.exists(P.OPTIMISED_FILE):  # ours at 0.7 and PathPlanner come from --pp-compare's run
            P.prepare_optimised(pool, names)
        out["optimiser"] = P.prepare_optimised(pool, names, tools=[f"ours@{m:g}" for m in P.MU_SWEEP[1:]],
                                               path=P.MU_FILE)
        print("optimised", f"({time.time() - t0:.0f} s)", flush=True)
        plan = [(n, k, s, pose) for pose in ("truth", "odom") for n in names for k in ks for s in seeds]
        plan += [(n, k, s, "slipodom") for n in courses for k in ks + PP_REF for s in seeds]
        res = pool.map(P._job, plan, chunksize=1)
    for (n, k, _, pose), row in zip(plan, res):
        out["runs"].setdefault(pose, {}).setdefault(n, {}).setdefault(k, []).append(row)
    out["runs"] = {pose: {n: {k: agg(v) for k, v in ks_.items()} for n, ks_ in ns.items()}
                   for pose, ns in out["runs"].items()}
    out["meta"]["wall_s"] = time.time() - t0
    return out


def _mean(rows, key):
    v = [r[key + "_mean"] for r in rows if r[key + "_mean"] is not None]
    return (float(np.mean(v)) if v else float("nan")), len(v)


def overall(runs, names, k):
    """Means over the targets of each target's mean (settled: over the targets where some run settled)."""
    rows = [runs[n][k] for n in names]
    t5, n5 = _mean(rows, "t_5cm")
    ts, ns = _mean(rows, "t_settle")
    every = sum(1 for r in rows if r["t_settle_nan"] == 0)
    return {"t5": t5, "n5": n5, "ts": ts, "ns": ns, "every": every, "n": len(rows),
            "err": _mean(rows, "err_end_cm")[0], "over": max(r["overshoot_cm_worst"] for r in rows),
            "slip": _mean(rows, "wheel_slip_ms")[0]}


def label(k):
    return P.METHODS[k][1]


def summary_table(runs, names, ks):
    L = ["| method | to 5 cm s | settled s (targets settled every seed) | end error cm | worst overshoot cm | "
         "wheel slip ms |", "|---|---|---|---|---|---|"]
    for k in ks:
        o = overall(runs, names, k)
        L.append(f"| {label(k)} | {o['t5']:.2f} | {o['ts']:.2f} ({o['every']}/{o['n']}) | {o['err']:.1f} | "
                 f"{o['over']:.1f} | {o['slip']:.0f} |")
    return "\n".join(L)


def course_table(runs, name, ks):
    from ppcompare import _t

    L = ["| method | to 5 cm s | settled s | end error cm mean / worst | overshoot worst cm | wheel slip ms |",
         "|---|---|---|---|---|---|"]
    for k in ks:
        a = runs[name][k]
        L.append(f"| {label(k)} | {_t(a, 't_5cm')} | {_t(a, 't_settle')} | {a['err_end_cm_mean']:.1f} / "
                 f"{a['err_end_cm_worst']:.1f} | {a['overshoot_cm_worst']:.1f} | {a['wheel_slip_ms_mean']:.0f} |")
    return "\n".join(L)


def section_md(out, ppc):
    """The RESULTS.md block. ppc = out/ppcompare.json (PathPlanner's rows for perfect pose and odometry)."""
    names, courses = out["meta"]["targets"], out["meta"]["courses"]
    ks = out["meta"]["keys"]
    titles = {"truth": "Perfect pose", "odom": "Wheel odometry + gyro", "slipodom": "Slip-aware odometry + IMU"}
    L = [MU_START, f"_Generated by `python bench/run.py --mu-sweep` ({len(out['meta']['seeds'])} seeds per cell, "
         f"{out['meta']['wall_s']:.0f} s wall)._\n",
         "Ours with the robot file's grip at mu " + ", ".join(f"{m:g}" for m in P.MU_SWEEP)
         + f" ({P.OURS_MU:g} as shipped), as drawn and optimised (the optimiser re-run per mu, default budget, seed 1). "
         "The output limiter's grip option is max(1.0, mu). "
         f"The plant's grip is mu {RP.mu_static:g} static / {RP.mu_kinetic:g} kinetic (less on the low-grip course, "
         "and from halfway on the grip-drop course). Means over all --pp-compare targets; PathPlanner's rows are "
         "from the --pp-compare run.\n"]
    for pose in ("truth", "odom"):
        L.append(f"### {titles[pose]}: all targets\n")
        runs = dict(out["runs"][pose])
        for n in names:
            runs[n] = dict(runs[n], **{k: ppc["runs"][pose][n][k] for k in PP_REF})
        L.append(summary_table(runs, names, ks + PP_REF) + "\n")
    L.append(f"### {titles['slipodom']}: the bench courses\n")
    L.append(summary_table(out["runs"]["slipodom"], courses, ks + PP_REF) + "\n")
    for c in ("low_grip_s_curve", "grip_drop_s_curve"):
        for pose in ("truth", "odom", "slipodom"):
            r = dict(out["runs"][pose][c])
            if pose != "slipodom":  # PathPlanner's slip-aware rows are run here; the others come from --pp-compare
                r.update({k: ppc["runs"][pose][c][k] for k in PP_REF})
            L.append(f"**{c}**, {titles[pose]}: {COURSES[c].description}\n")
            L.append(course_table({c: r}, c, ks + PP_REF) + "\n")
    L.append("Planned time before -> after the optimiser, summed over the target's path files:\n")
    L.append("| target | " + " | ".join(f"mu {m:g}" for m in P.MU_SWEEP[1:]) + " |")
    L.append("|---|" + "---|" * (len(P.MU_SWEEP) - 1))
    for n, tools in out["optimiser"].items():
        cells = []
        for m in P.MU_SWEEP[1:]:
            pairs = [tuple(float(v) for v in x.split(": ")[1].split(" (")[0].replace(" s", "").split(" -> "))
                     for x in tools[f"ours@{m:g}"]]
            b0, b1 = sum(p[0] for p in pairs), sum(p[1] for p in pairs)
            cells.append(f"{b0:.2f} -> {b1:.2f}")
        L.append(f"| {n} | " + " | ".join(cells) + " |")
    L.append("")
    L.append(MU_END)
    return "\n".join(L)


def write_md(out, ppc):
    text = open(MD, encoding="utf-8").read()
    block = section_md(out, ppc)
    if MU_START in text:
        i, j = text.index(MU_START), text.index(MU_END) + len(MU_END)
        text = text[:i] + block + text[j:]
    else:
        k = text.index("## Fidelity caveats")
        text = text[:k] + "## Planning grip: ours at several robot-file grips\n\n" + block + "\n\n" + text[k:]
    open(MD, "w", encoding="utf-8").write(text)


def main(seeds, procs):
    ppc = json.load(open(os.path.join(OUT, "ppcompare.json")))
    out = run(seeds, procs)
    with open(os.path.join(OUT, "musweep.json"), "w") as fh:
        json.dump(out, fh)
    write_md(out, ppc)
    print("wrote", os.path.join(OUT, "musweep.json"), "and the planning-grip block of", MD)
    return out

