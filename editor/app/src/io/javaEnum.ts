// The one piece of generated code: a PathName enum listing every path file, so robot code gets a
// compile error instead of a boot error when a path is renamed or deleted.

/** ToReef → TO_REEF, intake-2 → INTAKE_2. */
export function constantName(name: string): string {
  const snake = name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
  return /^[A-Z]/.test(snake) ? snake : `P_${snake}`;
}

export function pathNameEnum(javaPackage: string, names: readonly string[]): string {
  const sorted = [...names].sort();
  const used = new Set<string>();
  const constants = sorted.map((name) => {
    let c = constantName(name);
    for (let i = 2; used.has(c); i++) c = `${constantName(name)}_${i}`;
    used.add(c);
    return `  ${c}("${name}")`;
  });
  return [
    "// Generated by the 5712 path editor from src/main/deploy/paths. Don't edit: save in the editor instead.",
    `package ${javaPackage};`,
    "",
    "/** Every path file in deploy/paths. {@code PathLibrary.get(PathName.X.fileName())} loads one. */",
    "public enum PathName {",
    (constants.length > 0 ? constants.join(",\n") : "") + ";",
    "",
    "  private final String fileName;",
    "",
    "  PathName(String fileName) {",
    "    this.fileName = fileName;",
    "  }",
    "",
    "  /** The file name without .path.json, as PathLibrary.get takes it. */",
    "  public String fileName() {",
    "    return fileName;",
    "  }",
    "}",
    "",
  ].join("\n");
}

/** Where the enum goes in a robot project. */
export function enumPath(javaPackage: string): string {
  return `src/main/java/${javaPackage.split(".").join("/")}/PathName.java`;
}

export function isValidPackage(javaPackage: string): boolean {
  return /^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)*$/.test(javaPackage);
}
