// The one piece of generated code: PathEditorNames, a class of three enums (the path files, the event
// names the paths use, and the named points), so robot code names them with constants. A typo, or a path
// renamed in the editor, is then a compile error instead of a boot error. Each enum implements lib's
// PathId / EventId / PointId, which every name-taking method in lib accepts, and PathLibrary.loadAll()
// checks the constants against deploy at boot (a stale class fails there, naming what's missing).

/** The generated class's name (PathLibrary.NAMES_CLASS in lib). */
export const NAMES_CLASS = "PathEditorNames";

/** The enum the editor generated before PathEditorNames: removed on save. */
export const LEGACY_ENUM = "PathName";

/** ToReef → TO_REEF, intake-2 → INTAKE_2, "Score L (mirror)" → SCORE_L_MIRROR. */
export function constantName(name: string): string {
  const snake = name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
  return /^[A-Z]/.test(snake) ? snake : `N_${snake}`;
}

const javaString = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

/** One nested enum: a constant per name (sorted, collisions numbered), each carrying its exact name. */
function nestedEnum(enumName: string, iface: string, method: string, doc: string, names: readonly string[]): string[] {
  const sorted = [...new Set(names)].sort();
  const used = new Set<string>();
  const constants = sorted.map((name) => {
    let c = constantName(name);
    for (let i = 2; used.has(c); i++) c = `${constantName(name)}_${i}`;
    used.add(c);
    return `    ${c}(${javaString(name)})`;
  });
  return [
    `  /** ${doc} */`,
    `  public enum ${enumName} implements ${iface} {`,
    (constants.length > 0 ? constants.join(",\n") : "") + ";",
    "",
    "    private final String name;",
    "",
    `    ${enumName}(String name) {`,
    "      this.name = name;",
    "    }",
    "",
    "    @Override",
    `    public String ${method}() {`,
    "      return name;",
    "    }",
    "  }",
  ];
}

/** PathEditorNames.java for a project: its path files, the event names they use and its named points. */
export function namesFile(
  javaPackage: string,
  names: { readonly paths: readonly string[]; readonly events: readonly string[]; readonly points: readonly string[] },
): string {
  return [
    "// Generated by the 5712 path editor from src/main/deploy/paths. Don't edit: save in the editor instead.",
    `package ${javaPackage};`,
    "",
    "import frc.team5712.path.wpilib.EventId;",
    "import frc.team5712.path.wpilib.PathId;",
    "import frc.team5712.path.wpilib.PointId;",
    "",
    "/**",
    " * The project's names as constants: {@code paths.get(Paths.TO_REEF)}, {@code paths.bindEvent(Events.SHOOT, ...)},",
    ` * {@code otf.toPoint(drive, Points.SCORE_L, heading)}, with {@code import static ${javaPackage}.${NAMES_CLASS}.*}.`,
    " * PathLibrary.loadAll() checks them against deploy/paths at boot.",
    " */",
    `public final class ${NAMES_CLASS} {`,
    `  private ${NAMES_CLASS}() {}`,
    "",
    ...nestedEnum("Paths", "PathId", "fileName", "Every path file in deploy/paths (the name without .path.json).", names.paths),
    "",
    ...nestedEnum("Events", "EventId", "eventName", "Every event name the paths use.", names.events),
    "",
    ...nestedEnum("Points", "PointId", "pointName", "The editor's named points.", names.points),
    "}",
    "",
  ].join("\n");
}

/** Where a generated class goes in a robot project. */
export function javaPath(javaPackage: string, className: string = NAMES_CLASS): string {
  return `src/main/java/${javaPackage.split(".").join("/")}/${className}.java`;
}

export function isValidPackage(javaPackage: string): boolean {
  return /^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)*$/.test(javaPackage);
}
