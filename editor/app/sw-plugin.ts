// Writes dist/sw.js at build time: the service worker that lets the installed app (Edge/Chrome's
// "Install app") open offline. It precaches every file the build emitted plus public/ (but not the
// bench snapshot, which is cached the first time it's opened), and names its cache after a hash of
// them, so a new deploy replaces the old cache.

import { createHash } from "node:crypto";
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import type { Plugin } from "vite";

function filesUnder(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? filesUnder(p) : [p];
  });
}

export function serviceWorker(publicDir: string): Plugin {
  return {
    name: "path-editor-service-worker",
    apply: "build",
    generateBundle(_options, bundle) {
      const emitted = Object.keys(bundle);
      const extra = filesUnder(publicDir)
        .map((p) => relative(publicDir, p).split("\\").join("/"))
        .filter((p) => !p.startsWith("bench/") && p !== "sw.js");
      const files = ["", ...new Set([...emitted, ...extra])].map((f) => `/${f}`).sort();
      const version = createHash("sha256").update(files.join("\n")).update(JSON.stringify(emitted.map((f) => [f, (bundle[f] as { code?: string }).code?.length ?? 0]))).digest("hex").slice(0, 12);
      this.emitFile({ type: "asset", fileName: "sw.js", source: workerSource(version, files) });
    },
  };
}

function workerSource(version: string, files: string[]): string {
  return `// Generated by sw-plugin.ts at build time.
const CACHE = "path-editor-${version}";
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("path-editor-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  // pages: the network first (a new deploy shows at once), the cached app when offline
  if (req.mode === "navigate") {
    event.respondWith(fetch(req).catch(() => caches.match("/").then((r) => r || caches.match("/index.html"))));
    return;
  }
  // everything else: the cache first, then the network (and keep a copy of what it fetched)
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === "basic") {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}
